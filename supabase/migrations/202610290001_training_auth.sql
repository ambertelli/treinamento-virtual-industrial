-- Approval-based access for the institutional training app.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null default '',
  email text not null unique,
  status text not null default 'pendente' check (status in ('pendente','aprovado','bloqueado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.user_roles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','user')),
  unique(user_id, role)
);
alter table public.profiles enable row level security;
alter table public.user_roles enable row level security;

create or replace function public.has_role(_user_id uuid, _role text)
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.user_roles where user_id = _user_id and role = _role); $$;
revoke all on function public.has_role(uuid,text) from public;
grant execute on function public.has_role(uuid,text) to authenticated;

create policy "profiles self or admin read" on public.profiles for select to authenticated
using (auth.uid() = id or public.has_role(auth.uid(),'admin'));
create policy "admins update profile status" on public.profiles for update to authenticated
using (public.has_role(auth.uid(),'admin'))
with check (public.has_role(auth.uid(),'admin'));
create policy "users read own roles" on public.user_roles for select to authenticated
using (auth.uid() = user_id or public.has_role(auth.uid(),'admin'));

create or replace function public.handle_new_training_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, nome, email, status)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nome', new.raw_user_meta_data->>'full_name', ''),
    lower(new.email),
    case when lower(new.email) = 'ambertelli2000@hotmail.com' then 'aprovado' else 'pendente' end
  ) on conflict (id) do nothing;

  if lower(new.email) = 'ambertelli2000@hotmail.com' then
    insert into public.user_roles(user_id, role) values (new.id, 'admin')
    on conflict (user_id, role) do nothing;
  else
    insert into public.user_roles(user_id, role) values (new.id, 'user')
    on conflict (user_id, role) do nothing;
  end if;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created_training on auth.users;
create trigger on_auth_user_created_training
after insert on auth.users
for each row execute procedure public.handle_new_training_user();
